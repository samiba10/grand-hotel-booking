-- Portable SQL: runs unchanged on H2 (dev/test) and PostgreSQL (docker).
-- Money columns are BIGINT minor units (1050 = 10.50), never DECIMAL/FLOAT and never small ints.

CREATE TABLE hotels (
    id       BIGINT       PRIMARY KEY,
    name     VARCHAR(120) NOT NULL
);

CREATE TABLE rooms (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hotel_id    BIGINT      NOT NULL REFERENCES hotels (id),
    room_number VARCHAR(10) NOT NULL,
    room_type   VARCHAR(20) NOT NULL,
    status      VARCHAR(20) NOT NULL,
    CONSTRAINT uk_rooms_number UNIQUE (hotel_id, room_number),
    CONSTRAINT ck_rooms_type CHECK (room_type IN ('STANDARD', 'DELUXE', 'SUITE')),
    CONSTRAINT ck_rooms_status CHECK (status IN ('ACTIVE', 'MAINTENANCE'))
);

CREATE TABLE guests (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name VARCHAR(60)  NOT NULL,
    last_name  VARCHAR(60)  NOT NULL,
    email      VARCHAR(120) NOT NULL,
    phone      VARCHAR(30),
    CONSTRAINT uk_guests_email UNIQUE (email)
);

CREATE TABLE bookings (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    guest_id           BIGINT      NOT NULL REFERENCES guests (id),
    room_id            BIGINT      NOT NULL REFERENCES rooms (id),
    check_in           DATE        NOT NULL,
    check_out          DATE        NOT NULL,
    status             VARCHAR(20) NOT NULL,
    total_amount_minor BIGINT      NOT NULL CHECK (total_amount_minor >= 0),
    currency           VARCHAR(3)  NOT NULL,
    fx_rate_micros     BIGINT      NOT NULL CHECK (fx_rate_micros > 0),
    created_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_bookings_dates CHECK (check_out > check_in),
    CONSTRAINT ck_bookings_status CHECK (status IN ('CONFIRMED', 'CANCELLED'))
);

-- Supports the overlap query (availability + double-booking protection).
CREATE INDEX idx_bookings_room_dates ON bookings (room_id, status, check_in, check_out);
CREATE INDEX idx_bookings_guest ON bookings (guest_id);

CREATE TABLE audit_log (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    action           VARCHAR(50)  NOT NULL,
    entity_type      VARCHAR(50)  NOT NULL,
    entity_id        VARCHAR(120) NOT NULL,
    user_id          VARCHAR(50)  NOT NULL,
    timestamp        TIMESTAMP WITH TIME ZONE NOT NULL,
    transaction_id   VARCHAR(100),
    transaction_type VARCHAR(50),
    session_id       VARCHAR(100),
    outcome          INT,
    details          VARCHAR(500)
);

CREATE INDEX idx_audit_entity ON audit_log (entity_type, entity_id);
CREATE INDEX idx_audit_tx ON audit_log (transaction_id);
CREATE INDEX idx_audit_session ON audit_log (session_id);
